#!/usr/bin/env python3
"""Audit deletion scope/order from migration DDL (stdlib only; no DB/network).

The service re-derives and validates this graph against pg_constraint at runtime,
so ALTERs, composite FKs and schema drift cannot silently evade cleanup.
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[2]
tables, edges = {}, []
for path in sorted((root / 'migrations').glob('*.sql')):
    sql = re.sub(r'--[^\n]*', '', path.read_text())
    for statement in sql.split(';'):
        match = re.search(r'\b(CREATE TABLE(?: IF NOT EXISTS)?|ALTER TABLE)\s+(\w+)', statement, re.I)
        if not match:
            continue
        table = match[2]
        body = statement[match.end():]
        tables.setdefault(table, False)
        if re.search(r'\borganization_id\s+UUID\b', body, re.I):
            tables[table] = True
        for fk in re.finditer(r'REFERENCES\s+(\w+)\s*\(([^)]+)\)(?:\s+ON DELETE\s+(CASCADE|RESTRICT|SET NULL|NO ACTION))?', body, re.I):
            edges.append({'child': table, 'parent': fk[1], 'action': (fk[3] or 'NO ACTION').upper(), 'migration': path.name})
selected = {'organizations', 'users'} | {t for t, scoped in tables.items() if scoped}
while True:
    expanded = selected | {e['child'] for e in edges if e['parent'] in selected}
    if expanded == selected:
        break
    selected = expanded
order, state = [], {}
def visit(table):
    if state.get(table) == 2:
        return
    if state.get(table) == 1:
        raise RuntimeError(f'Non-SET-NULL FK cycle at {table}; manual review required')
    state[table] = 1
    for edge in edges:
        if edge['parent'] == table and edge['child'] != table and edge['action'] != 'SET NULL' and edge['child'] in selected:
            visit(edge['child'])
    state[table] = 2
    order.append(table)
for table in sorted(selected):
    visit(table)
if '--go' in sys.argv:
    print('// Code generated by scripts/schema/organization-delete-plan.py --go; DO NOT EDIT.')
    print('package core\n\nvar migrationOrganizationDeleteOrder = []string{')
    for table in order:
        print('\t' + json.dumps(table) + ',')
    print('}')
    sys.exit(0)
print(json.dumps({'source': 'migrations/*.sql; runtime verified from pg_constraint', 'tenant_column_tables': sum(tables.values()), 'covered_tables': len(selected), 'delete_order': order}, indent=2))
